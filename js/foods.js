/* Search: token match, ranked by whole-word starts. Returns up to `limit` rows
   as objects {name, serving, kcal, p, c, f, src}. */
function searchFoods(query, myFoods, limit = 14) {
  const q = query.trim().toLowerCase();
  if (q.length < 2) return [];
  const tokens = q.split(/\s+/);
  const scored = [];

  const consider = (name, serving, kcal, p, c, f, src) => {
    const low = name.toLowerCase();
    let score = 0;
    for (const t of tokens) {
      const idx = low.indexOf(t);
      if (idx === -1) return;
      score += idx === 0 ? 3 : (low[idx - 1] === ' ' || low[idx - 1] === ',' ? 2 : 1);
    }
    if (src === 'mine') score += 4;
    scored.push({ name, serving, kcal, p, c, f, src, score });
  };

  (myFoods || []).forEach(m => consider(m.name, m.serving || 'custom', m.kcal, m.p || 0, m.c || 0, m.f || 0, 'mine'));
  FOODS_DB.forEach(r => consider(r[0], r[1], r[2], r[3], r[4], r[5], 'db'));

  scored.sort((a, b) => b.score - a.score || a.name.length - b.name.length);
  return scored.slice(0, limit);
}
